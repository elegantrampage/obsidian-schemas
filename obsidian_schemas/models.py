class GiftIdea(BaseEntity):
    """
    Gift idea entity - represents a gift idea for someone.

    Matches the Gift Idea.md template:
        type: gift-idea
        for:
        source:
        date_added: "{{date}}"
    """

    type: Literal["gift-idea"] = "gift-idea"
    # Note: 'for' is a Python keyword, so we use an alias
    for_person: str = Field(default="", alias="for")
    source: str = ""
    date_added: str = ""


class Meeting(BaseEntity):
    """
    Meeting entity - represents a meeting note (generated by Exocortex).

    This is generated by the transcript processor, not a template:
        type: meeting
        date: ""
        attendees: []
        topics: []
        meeting_id: ""
    """

    type: Literal["meeting"] = "meeting"
    date: str = ""
    attendees: List[str] = Field(default_factory=list)
    topics: List[str] = Field(default_factory=list)
    meeting_id: str = ""


# Type alias for all entity types
EntityType = Union[Person, Company, Book, Watch, Explore, GiftIdea, Meeting]

# Mapping from type string to model class
TYPE_TO_MODEL: dict[str, Type[BaseEntity]] = {
    "person": Person,
    "company": Company,
    "book": Book,
    "watch": Watch,
    "explore": Explore,
    "gift-idea": GiftIdea,
    "meeting": Meeting,
}


def get_model_for_type(type_name: str) -> Optional[Type[BaseEntity]]:
    """
    Get the Pydantic model class for a given type name.

    Args:
        type_name: The 'type' field value from frontmatter

    Returns:
        The corresponding model class, or None if unknown
    """
    return TYPE_TO_MODEL.get(type_name)
