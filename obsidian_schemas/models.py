"""
Pydantic models for Obsidian entity frontmatter.

These models match EXACTLY what currently exists in the Obsidian vault templates.
They use `extra = "allow"` for forward compatibility with additional fields.

Entity Types:
    - Person: Contact/person notes (@Name.md files)
    - Company: Organization notes (@CompanyName.md files)
    - Book: Reading list items (Title - Author.md files)
    - Watch: Films/series to watch
    - Explore: Links/topics to explore
    - GiftIdea: Gift ideas for people
    - Meeting: Meeting notes (generated by Exocortex)
"""

from typing import List, Optional, Literal, Union, Type
from datetime import date
from pydantic import BaseModel, ConfigDict, Field


class BaseEntity(BaseModel):
    """
    Base class for all Obsidian entity types.

    Allows extra fields for forward compatibility - any fields in the
    frontmatter that aren't in the model will be preserved.
    """

    model_config = ConfigDict(
        extra="allow",
        # Use enum values when serializing
        use_enum_values=True,
        # Allow population by field name or alias
        populate_by_name=True,
    )

    type: str
    tags: List[str] = Field(default_factory=list)


class Person(BaseEntity):
    """
    Person entity - represents a contact in the vault.

    Matches the person.md template:
        type: person
        name: ""
        aliases: []
        emails: []
        phones: []
        whatsapp: ""
        company: ""
        title: ""
        linkedin: ""
        roles: []
        tags: [person]
        created: "{{date}}"

    Roles:
        Array of role identifiers that modify assistant behavior for this contact.
        Roles affect priority levels, staleness thresholds, notification preferences,
        and trigger special behaviors (e.g., agenda generation for coaching clients).

        Defined roles: vip, coaching-client, family, investor, active

        Combination rules: When a person has multiple roles, the most restrictive
        staleness threshold applies, priority modifiers are additive (capped at p1),
        notifications are union (any role enables = enabled), and all special
        behaviors apply.
    """

    type: Literal["person"] = "person"
    name: str = ""
    aliases: List[str] = Field(default_factory=list)
    emails: List[str] = Field(default_factory=list)
    phones: List[str] = Field(default_factory=list)
    whatsapp: str = ""
    company: str = ""
    title: str = ""
    linkedin: str = ""
    roles: List[str] = Field(default_factory=list)
    created: str = ""

    def get_primary_email(self) -> Optional[str]:
        """Get the first email address if available."""
        return self.emails[0] if self.emails else None

    def get_primary_phone(self) -> Optional[str]:
        """Get the first phone number if available."""
        return self.phones[0] if self.phones else None

    def has_role(self, role: str) -> bool:
        """Check if person has a specific role."""
        return role in self.roles

    def has_any_role(self, *roles: str) -> bool:
        """Check if person has any of the specified roles."""
        return any(r in self.roles for r in roles)

    def to_entity_id(self) -> str:
        """Generate a stable entity ID for graph databases."""
        return f"person_{self.name.lower().replace(' ', '_')}"


