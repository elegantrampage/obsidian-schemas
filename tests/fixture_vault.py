@dataclass(frozen=True)
class Verdict:
    """What a corruption specimen must produce, declared rather than observed."""

    kind: str            # "refusal" | "cleaned" | "loads"
    pattern: str = ""    # kind == "refusal": the NameGateRefusal.pattern expected
    cleaned: str = ""    # kind == "cleaned": clean_person_name's expected output


@dataclass(frozen=True)
class NoteSpec:
    """One corpus member's declared oracle.

    `shape_classes` and `discriminator` are two fields because AC-1(c) and
    AC-3(i) ask two different questions. AC-1(c) asks whether a note whose
    stored `name:` trips a live Tier-1 branch is present and NAMED as such — a
    fact about the DOOR, true whatever the live vault holds. AC-3(i) asks
    whether the corpus's declared class coverage equals the census's MEASURED
    rows — a fact about the VAULT. The landed census rules `arrow_connective`
    and `path_hostile` ABSENT, so one field could not answer both.
    """

    declared_type: Optional[str]
    fields: Optional[dict] = None
    undeclared: dict = field(default_factory=dict)
    shape_classes: tuple = ()
    discriminator: str = ""
    verdict: Optional[Verdict] = None
    roundtrip_representative: bool = False
    raw_bytes_hex: Optional[str] = None


