def materialize_vault(dest) -> Path:
    """Byte-copy the flat corpus into a caller-supplied directory.

    ADDS, never empties: a second call against the same `dest` overwrites each
    corpus member with identical bytes and leaves everything else in that
    directory alone. There is no `rmtree`, no glob-and-unlink and no "clean
    first" branch, and none may be added — emptying a caller-supplied directory
    is a destructive act a fixture helper has no business performing, and
    AC-1(b) asserts both halves.

    Never `shutil.copy2` (which carries mode and mtime the corpus does not
    declare), never `read_text`/`write_text` (which would raise on the non-UTF-8
    member and normalise line endings on the others), and never
    `write_markdown_file`, `write_frontmatter`, `repo.save()` or `create_stub` —
    those route through `gate_write` (`writer.py:252-253`), which is exactly
    what refuses half of this corpus.
    """
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    for src in sorted(CORPUS_ROOT.iterdir()):
        if src.is_file():
            (dest / src.name).write_bytes(src.read_bytes())
    return dest


def corpus_digest(root: Path = CORPUS_ROOT) -> str:
    """`sha256` over the sorted (filename, bytes) pairs, each NUL-framed.

    The framing is not decoration: without a separator, a rename that moves
    bytes between the name field and the content field produces the same digest.
    The walk is the SAME walk `materialize_vault` performs, which is what lets
    AC-1(b) compare the digest over the materialized tree against this constant
    with no second traversal rule to keep in step.
    """
    digest = hashlib.sha256()
    for path in sorted((p for p in Path(root).iterdir() if p.is_file()),
                       key=lambda p: p.name):
        digest.update(path.name.encode("utf-8"))
        digest.update(b"\x00")
        digest.update(path.read_bytes())
        digest.update(b"\x00")
    return digest.hexdigest()
